import argparse
import os
import shutil
import sys

from torch.utils.hipify.hipify_python import get_hip_file_path, hipify


def _expected_hip_build_path(source_abs: str, output_directory: str) -> str:
    """Match torch.utils.hipify.hipify_python.preprocessor fout_path naming."""
    rel = os.path.relpath(source_abs, output_directory)
    return os.path.abspath(
        os.path.join(
            output_directory, get_hip_file_path(rel, is_pytorch_extension=True)
        )
    )


HIPIFY_C_BREADCRUMB_LINE = (
    "// !!! This is a file automatically generated by hipify!!!"
)


def _rewrite_vendor_macro_injection(
    output_dir: str, macro_header: str, dispatch_header: str
) -> None:
    """Rewrite the vendor translator's auto-injected SDK macro include.

    GENERATED files are recognized by the public hipify breadcrumb
    (``// !!! This is a file automatically generated by hipify!!!``) on
    their FIRST line — never by position alone, so an AUTHORED file
    whose first line happens to be the same include is left untouched.

    The vendor translator injects ``#include <macro_header>`` adjacent
    to the breadcrumb (immediately after it, allowing blank lines).
    Only that injected include is rewritten — to a per-file relative
    include of the build-dir DISPATCH header, which selects at
    preprocessing time:

        stable TUs (TORCH_TARGET_VERSION / TORCH_STABLE_ONLY defined)
          -> the numeric-only shim generated by cmake/hcu_macro_shim.py
        legacy TUs -> the original SDK header, unchanged

    Safety:
    - symlinks under the output tree are NOT followed (a symlink
      escaping the generated tree is skipped — no cross-tree rewrite);
    - original source trees and installed Torch/SDK files are never
      modified (only files physically under output_dir are touched);
    - idempotent: already-rewritten files no longer carry the injected
      include at the recognized position and are skipped;
    - empty option -> this function is never called (previous
      behavior byte-identical).
    """
    output_root = os.path.abspath(output_dir)
    dispatch_abs = os.path.abspath(dispatch_header)
    injected_line = f"#include <{macro_header}>"
    breadcrumb = HIPIFY_C_BREADCRUMB_LINE

    rewrote = 0
    for root, dirs, files in os.walk(output_root, followlinks=False):
        # prune symlinked directories (escape guard)
        dirs[:] = [
            d for d in dirs
            if not os.path.islink(os.path.join(root, d))
        ]
        for fname in files:
            path = os.path.join(root, fname)
            if os.path.islink(path):
                continue  # never follow/rewrite through a symlink
            if not fname.endswith((".hip", ".h", ".cu", ".cuh", ".cpp",
                                   ".cc")):
                continue
            try:
                with open(path, "r", encoding="utf-8",
                          errors="strict") as f:
                    text = f.read()
            except (UnicodeDecodeError, OSError):
                continue
            lines = text.split("\n")
            # GENERATED-file marker: the public hipify breadcrumb on
            # line 1. Without it, this is not a generated file — leave
            # it untouched (authored first-line includes included).
            if not lines or lines[0].strip() != breadcrumb:
                continue
            # find the injected include ADJACENT to the breadcrumb
            # (immediately after, allowing blank lines)
            idx = None
            for k in range(1, min(len(lines), 4)):
                stripped = lines[k].strip()
                if stripped == "":
                    continue
                if stripped == injected_line:
                    idx = k
                break
            if idx is None:
                continue
            # per-file relative include of the dispatch header so
            # generated NESTED headers rewrite correctly too
            rel = os.path.relpath(
                dispatch_abs, os.path.dirname(path) or ".")
            lines[idx] = f'#include "{rel}"'
            with open(path, "w", encoding="utf-8") as f:
                f.write("\n".join(lines))
            rewrote += 1

    # Emit the dispatch header (build-dir only). It includes the shim
    # by fixed name; both live in the seam directory which CMake adds
    # to the include path. The dispatch NEVER references an
    # ungenerated shim at build time: CMake orders the shim generation
    # before the hipify target (see cmake/utils.cmake).
    os.makedirs(os.path.dirname(dispatch_abs), exist_ok=True)
    with open(dispatch_abs, "w", encoding="utf-8") as f:
        f.write(
            "// GENERATED at build time by cmake/hipify.py — EXPERIMENTAL HCU\n"
            "// stable/legacy dispatch for the vendor SDK macro header.\n"
            "// Build-directory-only; do not version.\n"
            "#ifndef VLLM_HCU_MACRO_DISPATCH_H_\n"
            "#define VLLM_HCU_MACRO_DISPATCH_H_\n"
            "#if defined(TORCH_TARGET_VERSION) || defined(TORCH_STABLE_ONLY)\n"
            "// Stable-libtorch TU: numeric-only shim (generated by\n"
            "// cmake/hcu_macro_shim.py from the installed SDK header).\n"
            '// The shim sits next to this dispatch header (same build dir;\n'
            '// CMake adds that dir to the include path and orders the shim\n'
            '// generation before the hipify rewrite).\n'
            '#include "hcu_macro_shim.h"\n'
            "#else\n"
            "// Legacy TU: the original vendor SDK header, unchanged.\n"
            f"#include <{macro_header}>\n"
            "#endif\n"
            "#endif // VLLM_HCU_MACRO_DISPATCH_H_\n"
        )
    print(
        f"[hcu-macro-seam] rewrote {rewrote} generated file(s); "
        f"dispatch header at {dispatch_abs}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()

    # Project directory where all the source + include files live.
    parser.add_argument(
        "-p",
        "--project_dir",
        help="The project directory.",
    )

    # Directory where hipified files are written.
    parser.add_argument(
        "-o",
        "--output_dir",
        help="The output directory.",
    )

    # Source files to convert.
    parser.add_argument(
        "sources", help="Source files to hipify.", nargs="*", default=[]
    )

    # EXPERIMENTAL HCU macro-header seam (default empty = off).
    parser.add_argument(
        "--hcu-macro-header",
        default="",
        help="EXPERIMENTAL: relative include name of the vendor SDK macro "
        "header auto-injected by the vendor translator into generated "
        "HIP sources. When set, the injected include at the injection "
        "position (first line) of GENERATED build outputs is rewritten "
        "to include the stable/legacy dispatch header instead.",
    )
    parser.add_argument(
        "--hcu-dispatch-header",
        default="",
        help="Build-directory path of the dispatch header to substitute "
        "for the auto-injected vendor include (required with "
        "--hcu-macro-header).",
    )

    args = parser.parse_args()
    if args.hcu_macro_header and not args.hcu_dispatch_header:
        parser.error(
            "--hcu-dispatch-header is required with --hcu-macro-header")

    # Limit include scope to project_dir only
    includes = [os.path.join(args.project_dir, "*")]

    # Get absolute path for all source files.
    extra_files = [os.path.abspath(s) for s in args.sources]

    # Copy sources from project directory to output directory.
    # The directory might already exist to hold object files so we ignore that.
    shutil.copytree(args.project_dir, args.output_dir, dirs_exist_ok=True)

    hipify_result = hipify(
        project_directory=args.project_dir,
        output_directory=args.output_dir,
        # Hipify resolves quoted includes next to the including file first; vLLM
        # uses paths relative to csrc/ (e.g. "libtorch_stable/torch_utils.h"
        # from quantization/w8a8/fp8/*.cu). Without an include root here, those
        # headers are never found and are not hipified or rewritten in dependents.
        header_include_dirs=["."],
        includes=includes,
        extra_files=extra_files,
        show_detailed=True,
        is_pytorch_extension=True,
        hipify_extra_files_only=True,
    )

    hipified_sources = []
    for source in args.sources:
        s_abs = os.path.abspath(source)
        if s_abs in hipify_result and hipify_result[s_abs].hipified_path is not None:
            path = hipify_result[s_abs].hipified_path
            # PyTorch skips writing when is_pytorch_extension and text unchanged;
            # hipified_path then stays *.cu. CMake expects *.hip under output_dir.
            if s_abs.endswith(".cu") and path.endswith(".cu"):
                dest = _expected_hip_build_path(s_abs, args.output_dir)
                if os.path.normpath(path) != os.path.normpath(dest):
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    shutil.copy2(path, dest)
                hipified_s_abs = dest
            else:
                hipified_s_abs = path
        else:
            hipified_s_abs = s_abs
        hipified_sources.append(hipified_s_abs)

    assert len(hipified_sources) == len(args.sources)

    # EXPERIMENTAL HCU macro-header seam (empty option -> exactly the
    # previous behavior; this whole block is skipped).
    if getattr(args, "hcu_macro_header", None):
        _rewrite_vendor_macro_injection(
            output_dir=args.output_dir,
            macro_header=args.hcu_macro_header,
            dispatch_header=args.hcu_dispatch_header,
        )

    # Print hipified source files.
    print("\n".join(hipified_sources))
