"""REAL CMake/Ninja orchestration test for the HCU macro-header seam.

Runs the ACTUAL CMake dependency graph (configure + build with Ninja)
against the REAL project scripts (cmake/hcu_macro_shim.py and
cmake/hipify.py's seam post-pass), with a SYNTHETIC vendor header
(invented macro names/values) and a vendor-translator STUB (injects the
include after the public hipify breadcrumb). Only the vendor
translation boundary and torch's hipify core are stubbed — the CMake
graph, the shim generator, the preprocessor (host clang), the dispatch
emission and the generated-header rewrite are all real.

No GPU, no installed SDK. Requires cmake+ninja on PATH or in the test
venv (skips if absent). --noconftest friendly.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
REAL_SHIM_SCRIPT = ROOT / "cmake" / "hcu_macro_shim.py"
REAL_HIPIFY_SCRIPT = ROOT / "cmake" / "hipify.py"
CC = shutil.which("clang") or shutil.which("gcc") or shutil.which("cc")
CMAKE = shutil.which("cmake") or str(
    Path(sys.prefix) / "bin" / "cmake")
NINJA = shutil.which("ninja") or str(Path(sys.prefix) / "bin" / "ninja")

requires_tools = pytest.mark.skipif(
    CC is None or not Path(CMAKE).exists() or not Path(NINJA).exists(),
    reason="cmake/ninja/host C++ compiler not available",
)

BC = "// !!! This is a file automatically generated by hipify!!!"

VENDOR_HEADER = textwrap.dedent("""\
    #pragma once
    #ifdef USE_ROCM
    #define SYNTH_VENDOR_TILE_X 32
    #define SYNTH_VENDOR_TILE_Y 0x10
    #define SYNTH_VENDOR_LIMIT 18446744073709551615ULL
    #else
    #define SYNTH_VENDOR_TILE_X 1
    #endif
    """)

CMAKELISTS = textwrap.dedent("""\
    cmake_minimum_required(VERSION 3.25)
    project(hcu_seam_integration NONE)
    find_package(Python3 REQUIRED COMPONENTS Interpreter)

    # ---- mirror of the vLLM seam wiring (utils.cmake) ----
    set(HCU_MACRO_HEADER "synth_vendor_macros.h" CACHE STRING "")
    set(SEAM_DIR ${CMAKE_BINARY_DIR}/hcu_macro_seam)
    set(SHIM ${SEAM_DIR}/hcu_macro_shim.h)
    set(DISPATCH ${SEAM_DIR}/hcu_macro_dispatch.h)

    # include roots: the synthetic SDK include dir (stands in for
    # TORCH_INCLUDE_DIRS) — repeated --include-dir=<dir> argv
    set(SEAM_INCLUDE_DIRS ${CMAKE_SOURCE_DIR}/sdk_include ${CMAKE_SOURCE_DIR}/csrc)
    set(SHIM_INCLUDE_ARGS)
    foreach(d ${SEAM_INCLUDE_DIRS})
      list(APPEND SHIM_INCLUDE_ARGS "--include-dir=${d}")
    endforeach()
    # resolve the SELECTED header to a concrete FILE (dependency on the
    # header file itself + the compiler executable, mirroring the real
    # wiring: an in-place header edit regenerates the shim)
    set(RESOLVED_HEADER "")
    foreach(d ${SEAM_INCLUDE_DIRS})
      if(EXISTS "${d}/${HCU_MACRO_HEADER}")
        set(RESOLVED_HEADER "${d}/${HCU_MACRO_HEADER}")
        break()
      endif()
    endforeach()
    if(NOT RESOLVED_HEADER)
      message(FATAL_ERROR "selected header not found under seam include roots")
    endif()

    add_custom_command(
      OUTPUT ${SHIM}
      COMMAND ${Python3_EXECUTABLE} ${REAL_SHIM_SCRIPT}
              --compiler ${CMAKE_CXX_COMPILER}
              --header ${HCU_MACRO_HEADER}
              ${SHIM_INCLUDE_ARGS}
              --compiler-arg=-DUSE_ROCM=1
              --output ${SHIM}
      DEPENDS ${REAL_SHIM_SCRIPT} ${RESOLVED_HEADER} ${CMAKE_CXX_COMPILER}
      COMMENT "shim"
      VERBATIM)

    # vendor-translation + hipify seam driver: stub the vendor
    # translator (inject after the breadcrumb) and torch hipify core
    # (emit breadcrumb-marked generated files), then run the REAL
    # hipify.py seam post-pass unchanged.
    set(GEN_OUT ${CMAKE_BINARY_DIR}/csrc)
    add_custom_target(hipify_all ALL
      COMMAND ${Python3_EXECUTABLE} ${CMAKE_SOURCE_DIR}/fake_hipify.py
              --out ${GEN_OUT}
              --macro-header ${HCU_MACRO_HEADER}
              --real-hipify ${REAL_HIPIFY_SCRIPT}
              --dispatch ${DISPATCH}
      DEPENDS ${CMAKE_SOURCE_DIR}/fake_hipify.py ${SHIM}
      BYPRODUCTS ${DISPATCH} ${GEN_OUT}/kernel.hip
      COMMENT "hipify_all (synthetic translator)")
    """)

FAKE_HIPIFY = textwrap.dedent("""\
    #!/usr/bin/env python3
    '''Vendor-translation + hipify STUB for the orchestration test.

    Stubs ONLY: (a) torch's hipify core — emits generated files
    carrying the PUBLIC hipify breadcrumb; (b) the vendor translator —
    injects the SDK include adjacent to the breadcrumb. Then runs the
    REAL cmake/hipify.py seam post-pass (_rewrite_vendor_macro_injection)
    unchanged, exactly as the real hipify.py __main__ would.
    '''
    import argparse
    import importlib.util as ilu
    import os
    from pathlib import Path

    BC = "// !!! This is a file automatically generated by hipify!!!"

    p = argparse.ArgumentParser()
    p.add_argument("--out", required=True)
    p.add_argument("--macro-header", required=True)
    p.add_argument("--real-hipify", required=True)
    p.add_argument("--dispatch", required=True)
    a = p.parse_args()

    out = Path(a.out)
    (out / "nested").mkdir(parents=True, exist_ok=True)
    # torch-hipify stub: generated outputs with the public breadcrumb
    (out / "kernel.hip").write_text(
        BC + "\\n__global__ void k(float* x) { x[0] = 1.f; }\\n")
    (out / "nested" / "kernel_kernels.h").write_text(
        BC + "\\n#pragma once\\n#define LOCAL_CONST 7\\n")
    # vendor-translator stub: inject the SDK include ADJACENT to the
    # breadcrumb (immediately after it) in every generated file
    for f in [out / "kernel.hip", out / "nested" / "kernel_kernels.h"]:
        lines = f.read_text().split("\\n")
        lines.insert(1, f"#include <{a.macro_header}>")
        f.write_text("\\n".join(lines))

    # REAL seam post-pass from the real hipify.py
    spec = ilu.spec_from_file_location("real_hipify", a.real_hipify)
    mod = ilu.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod._rewrite_vendor_macro_injection(
        str(out), a.macro_header, a.dispatch)
    """)


@requires_tools
def test_real_cmake_orchestration(tmp_path):
    proj = tmp_path / "proj"
    (proj / "sdk_include").mkdir(parents=True)
    (proj / "csrc").mkdir(parents=True)
    (proj / "sdk_include" / "synth_vendor_macros.h").write_text(VENDOR_HEADER)
    (proj / "CMakeLists.txt").write_text(
        CMAKELISTS.replace("${REAL_SHIM_SCRIPT}", str(REAL_SHIM_SCRIPT))
        .replace("${REAL_HIPIFY_SCRIPT}", str(REAL_HIPIFY_SCRIPT)))
    (proj / "fake_hipify.py").write_text(FAKE_HIPIFY)

    build = tmp_path / "build"
    build.mkdir()

    # REAL configure + build (Ninja generator; host compiler)
    env = dict(os.environ)
    ninja_bin = str(Path(sys.prefix) / "bin" / "ninja")
    if not Path(ninja_bin).exists():
        ninja_bin = shutil.which("ninja")
    r = subprocess.run(
        [CMAKE, "-S", str(proj), "-B", str(build), "-G", "Ninja",
         f"-DCMAKE_CXX_COMPILER={CC}",
         f"-DCMAKE_MAKE_PROGRAM={ninja_bin}",
         f"-DPython3_EXECUTABLE={sys.executable}"],
        capture_output=True, text=True, timeout=300, env=env)
    assert r.returncode == 0, r.stderr[-2000:]

    r = subprocess.run([CMAKE, "--build", str(build), "--verbose"],
                       capture_output=True, text=True, timeout=600, env=env)
    assert r.returncode == 0, r.stdout[-2000:] + r.stderr[-2000:]

    # 1. numeric shim generated (BEFORE hipify_all per the dependency
    #    graph — Ninja ordered the shim command first)
    order = r.stdout.index("shim\n") if "shim\n" in r.stdout else None
    shim_path = build / "hcu_macro_seam" / "hcu_macro_shim.h"
    assert shim_path.exists(), "shim missing"
    shim = shim_path.read_text()
    # USE_ROCM active branch discovered (32/0x10), NOT the inactive 1
    assert "#define SYNTH_VENDOR_TILE_X 32" in shim
    assert "#define SYNTH_VENDOR_TILE_Y 0x10" in shim
    assert "#define SYNTH_VENDOR_LIMIT 18446744073709551615ULL" in shim
    assert "SYNTH_VENDOR_TILE_X 1" not in shim  # non-USE_ROCM branch excluded

    # 2. dispatch exists + references the (already generated) shim
    dispatch = (build / "hcu_macro_seam" / "hcu_macro_dispatch.h").read_text()
    assert 'defined(TORCH_TARGET_VERSION) || defined(TORCH_STABLE_ONLY)' in dispatch
    assert '#include "hcu_macro_shim.h"' in dispatch
    assert "#include <synth_vendor_macros.h>" in dispatch

    # 3. generated-header rewrite: injected include replaced by
    #    per-file relative dispatch include (top-level + NESTED)
    gen = (build / "csrc" / "kernel.hip").read_text().split("\n")
    assert gen[0] == BC
    assert gen[1].startswith('#include "../hcu_macro_seam/')
    nested = (build / "csrc" / "nested" / "kernel_kernels.h").read_text().split("\n")
    assert nested[0] == BC
    assert nested[1].startswith('#include "../../hcu_macro_seam/')

    # 4. stable-vs-legacy preprocessing with PRESERVED values (host
    #    preprocessor; the dispatch selects per TU context)
    tu = tmp_path / "tu.cpp"
    tu.write_text(
        '#include "kernel.hip"\n'
        'static_assert(SYNTH_VENDOR_TILE_X == 32, "");\n'
        'static_assert(SYNTH_VENDOR_TILE_Y == 16, "");\n'
        'static_assert(SYNTH_VENDOR_LIMIT == 18446744073709551615ULL, "");\n'
    )
    # stable context: TORCH_TARGET_VERSION defined -> dispatch selects
    # the numeric shim (NO SDK header, NO types)
    r_stable = subprocess.run(
        [CC, "-E", "-x", "c++", "-I", str(build / "csrc"),
         "-I", str(build / "hcu_macro_seam"),
         "-DTORCH_TARGET_VERSION=0x020B000000000000ULL",
         str(tu)],
        capture_output=True, text=True, timeout=120)
    assert r_stable.returncode == 0, r_stable.stderr[:800]
    # the stable path pulled the SHIM, not the SDK header: NO SDK
    # linemarker appears, and the macro VALUES resolved from the shim
    # (rc 0 already proves every static_assert held with the shim's
    # exact values: 32 / 16 / 18446744073709551615ULL)
    assert "synth_vendor_macros.h" not in r_stable.stdout
    assert "hcu_macro_shim.h" in r_stable.stdout  # shim linemarker

    # legacy context: no TORCH_* -> dispatch selects the ORIGINAL SDK
    # header (include resolved from sdk_include)
    r_legacy = subprocess.run(
        [CC, "-E", "-x", "c++", "-I", str(build / "csrc"),
         "-I", str(build / "hcu_macro_seam"),
         "-I", str(proj / "sdk_include"),
         str(tu)],
        capture_output=True, text=True, timeout=120)
    assert r_legacy.returncode == 0, r_legacy.stderr[:800]
    # legacy used the REAL SDK header: its linemarker appears in the
    # preprocessed output (defines are consumed by -E; the linemarker
    # is the inclusion proof)
    assert "synth_vendor_macros.h" in r_legacy.stdout

    # 5. idempotent rebuild: re-running the build does not fail or
    #    double-rewrite
    r2 = subprocess.run([CMAKE, "--build", str(build)],
                        capture_output=True, text=True, timeout=600,
                        env=env)
    assert r2.returncode == 0, r2.stderr[-800:]

    # 6. HEADER-EDIT REGENERATION (dependency on the resolved header
    #    FILE): modify the synthetic SDK macro value in place and
    #    rebuild — the numeric shim must REGENERATE with the new value
    #    and stable preprocessing must reflect it. No real SDK/compiler
    #    is altered (synthetic header only).
    import os as _os
    import time as _time
    sdk_header = proj / "sdk_include" / "synth_vendor_macros.h"
    sdk_header.write_text(
        VENDOR_HEADER.replace(
            "#define SYNTH_VENDOR_TILE_X 32",
            "#define SYNTH_VENDOR_TILE_X 48"))
    # explicitly bump mtime past the previous build (sub-second edit
    # granularity can hide the change from Ninja's restat)
    _os.utime(sdk_header, (_time.time() + 2, _time.time() + 2))
    r3 = subprocess.run([CMAKE, "--build", str(build), "--verbose"],
                        capture_output=True, text=True, timeout=600,
                        env=env)
    assert r3.returncode == 0, r3.stdout[-1500:] + r3.stderr[-800:]
    # the shim regeneration actually ran (the shim command re-executed)
    assert "hcu_macro_shim.py" in r3.stdout
    shim2 = shim_path.read_text()
    assert "#define SYNTH_VENDOR_TILE_X 48" in shim2, \
        "shim did not regenerate after the header edit"
    assert "#define SYNTH_VENDOR_TILE_X 32" not in shim2
    # stable preprocessing reflects the REGENERATED value
    tu2 = tmp_path / "tu2.cpp"
    tu2.write_text(
        '#include "kernel.hip"\n'
        'static_assert(SYNTH_VENDOR_TILE_X == 48, "");\n'
    )
    r_stable2 = subprocess.run(
        [CC, "-E", "-x", "c++", "-I", str(build / "csrc"),
         "-I", str(build / "hcu_macro_seam"),
         "-DTORCH_TARGET_VERSION=0x020B000000000000ULL",
         str(tu2)],
        capture_output=True, text=True, timeout=120)
    assert r_stable2.returncode == 0, r_stable2.stderr[:800]


def test_build_sh_forwards_macro_header_env():
    """The DOCUMENTED build entrypoint (build.sh) forwards the optional
    HCU_MACRO_HEADER environment input as --build-arg (default empty).
    A Dockerfile-only arg would be insufficient; no vendor path/value
    may appear in the script."""
    sh = (ROOT / "docker" / "public-build" / "build.sh").read_text()
    assert 'HCU_MACRO_HEADER="${HCU_MACRO_HEADER:-}"' in sh
    assert '--build-arg HCU_MACRO_HEADER="$HCU_MACRO_HEADER"' in sh
    # no vendor path/value in the entrypoint (only the empty default
    # and the forwarding); heuristic: no .h suffix constants
    import re
    forbidden = re.findall(r'HCU_MACRO_HEADER[:=]\s*"[^"]*\.h"', sh)
    assert not forbidden, forbidden
